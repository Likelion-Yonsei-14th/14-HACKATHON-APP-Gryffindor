/**
 * [text] 안의 가벼운 마크다운(# 제목, ## 소제목, 빈 줄 구분)만 해석해서 렌더링한다.
 * 굵게(**...**) 표시는 지원하지 않고 별표는 그대로 지운다 — 법률 문서라 강조 스타일보다
 * 읽기 쉬운 줄바꿈/제목 구분이 더 중요하다고 판단.
 */
@Composable
internal fun TermsBody(text: String, textColor: Color) {
    Column {
        text.split("\n").forEach { rawLine ->
            val line = rawLine.replace("**", "")
            when {
                line.isBlank() -> Spacer(modifier = Modifier.height(12.dp))
                line.startsWith("## ") -> {
                    Text(
                        text = line.removePrefix("## "),
                        color = textColor,
                        fontSize = 16.sp,
                        fontWeight = FontWeight.Bold,
                        modifier = Modifier.padding(top = 4.dp, bottom = 4.dp),
                    )
                }
                line.startsWith("# ") -> {
                    Text(
                        text = line.removePrefix("# "),
                        color = textColor,
                        fontSize = 19.sp,
                        fontWeight = FontWeight.Bold,
                        modifier = Modifier.padding(bottom = 4.dp),
                    )
                }
                else -> {
                    Text(text = line, color = textColor, fontSize = 13.sp, lineHeight = 19.sp)
                }
            }
        }
    }
}
