회사는 운영상, 기술상 또는 법률상 필요한 경우 서비스의 전부 또는 일부를 변경하거나 중단할 수 있습니다.

회사는 서비스 내용, 이용 방법 또는 이용 시간에 변경이 있는 경우 변경 사유, 변경 내용 및 적용일자를 서비스 내 공지 등 합리적인 방법으로 안내합니다.

회사는 무료로 제공하는 서비스의 전부 또는 일부를 운영 정책상 변경하거나 중단할 수 있으며, 관계 법령에 특별한 규정이 없는 한 별도의 보상을 하지 않습니다.

## 제 15 조 (정보의 제공)

회사는 서비스 이용에 필요한 정보, 서비스 변경 사항, 보안 안내, 환급 절차 안내 및 공항 추천 관련 정보를 서비스 화면, 전자우편, 문자메시지 또는 알림 등의 방법으로 제공할 수 있습니다.

을은 마케팅 목적의 정보 수신을 거부할 수 있습니다. 다만, 서비스 이용에 필수적인 안내, 약관 변경, 보안 안내, 결제 관련 안내 및 개인정보 관련 안내는 수신 거부 여부와 관계없이 제공될 수 있습니다.

## 제 16 조 (지식재산권)

서비스 화면, 디자인, 상표, 프로그램, 데이터 구성, 콘텐츠 및 그 밖에 회사가 제공하는 자료에 관한 저작권과 지식재산권은 회사 또는 정당한 권리자에게 귀속됩니다.

을은 회사의 사전 동의 없이 서비스와 관련된 자료를 복제, 배포, 수정, 판매, 대여하거나 상업적으로 이용할 수 없습니다.

을이 서비스에 입력하거나 등록한 자료에 관한 책임은 을에게 있습니다. 을은 자신이 입력한 자료가 제3자의 권리를 침해하지 않도록 해야 합니다.

## 제 17 조 (이용계약의 해지)

회원은 언제든지 서비스 내 설정 화면 또는 회사가 정한 방법을 통해 회원 탈퇴를 요청할 수 있습니다.

회원이 탈퇴하는 경우 회사는 관계 법령 및 개인정보 처리방침에 따라 보관이 필요한 정보를 제외한 회원 정보를 처리합니다.

회원이 회원 탈퇴를 하더라도 법령상 보관이 필요한 기록, 분쟁 해결을 위해 필요한 기록 또는 부정 이용 방지를 위해 필요한 기록은 정해진 기간 동안 보관할 수 있습니다.

## 제 18 조 (이용 제한)

회사는 을이 이 약관의 의무를 위반하거나 서비스의 정상 운영을 방해한 경우 경고, 일시 이용 제한, 이용계약 해지 등 필요한 조치를 취할 수 있습니다.

회사는 다음 각 호의 경우 사전 안내 없이 서비스 이용을 제한하거나 이용계약을 해지할 수 있습니다.

1. 타인의 개인정보 또는 계정을 도용한 경우
2. 서비스 보안을 위협하거나 시스템을 해킹한 경우
3. 타인의 권리를 중대하게 침해한 경우
4. 불법 촬영 또는 촬영 제한 정책 위반이 확인된 경우
5. 관계 법령을 위반한 경우

을은 이용 제한 조치에 이의가 있는 경우 회사가 정한 방법으로 이의 신청을 할 수 있습니다.

## 제 19 조 (책임 제한)

회사는 천재지변, 전쟁, 테러, 통신 장애, 기기 오류, 외부 서비스 장애, 제휴 정보 변경 등 회사가 통제하기 어려운 사유로 서비스를 제공할 수 없는 경우 책임을 지지 않습니다.

회사는 을의 귀책사유로 발생한 서비스 이용 장애에 책임을 지지 않습니다.

회사는 을이 서비스에서 제공받은 상품 인식 결과, 예상 환급가, 환율 정보, 추천 결과 또는 체크리스트 정보를 근거로 내린 구매, 환급 신청 또는 이동 결정에 대해 책임을 지지 않습니다.

회사는 무료로 제공되는 서비스 이용과 관련하여 관계 법령에 특별한 규정이 없는 한 책임을 지지 않습니다.

## 제 20 조 (준거법 및 관할)

이 약관은 대한민국 법령을 따릅니다.

회사와 을 사이에 분쟁이 발생한 경우 상호 협의를 우선합니다.

협의로 해결되지 않는 분쟁은 관계 법령에 따른 관할 법원에 제기할 수 있습니다.
